"""
Upload data/raw to a Hugging Face dataset repo and publish an autogenerated datasheet.

Usage:
    export HF_TOKEN=hf_...
    python scripts/push_raw_dataset_to_hf.py --repo-id <user_or_org/dataset_name>
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import sys
import tempfile
from collections import defaultdict
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

from huggingface_hub import HfApi, create_repo


REPO_TYPE = "dataset"
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE_DIR = PROJECT_ROOT / "data" / "raw"
DEFAULT_REPO_ID = "nickil-shay-antonio/round-trip-code-compression-raw"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Upload data/raw to Hugging Face Datasets with an autogenerated datasheet."
    )
    parser.add_argument("--repo-id", default=DEFAULT_REPO_ID, help="Hugging Face dataset repo id.")
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=DEFAULT_SOURCE_DIR,
        help="Local folder to upload (default: data/raw).",
    )
    parser.add_argument(
        "--token-env",
        default="HF_TOKEN",
        help="Environment variable name that stores the HF token.",
    )
    parser.add_argument(
        "--public",
        action="store_true",
        help="Create the dataset repo as public (default: private).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print summary and datasheet preview without uploading.",
    )
    return parser.parse_args()


def list_files(root_dir: Path) -> List[Path]:
    return sorted(p for p in root_dir.rglob("*") if p.is_file())


def summarize_files(
    source_dir: Path,
    files: Iterable[Path],
) -> Tuple[Dict[str, Dict[str, int]], Dict[str, Dict[str, int]], int]:
    by_algo_split: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
    by_algo_ext: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
    total_bytes = 0

    for file_path in files:
        rel = file_path.relative_to(source_dir)
        parts = rel.parts
        algorithm = parts[0] if len(parts) >= 1 else "unknown"
        split_name = parts[1] if len(parts) >= 2 else "unknown"
        ext = file_path.suffix.lower().lstrip(".") or "no_ext"
        by_algo_split[algorithm][split_name] += 1
        by_algo_ext[algorithm][ext] += 1
        total_bytes += file_path.stat().st_size

    return by_algo_split, by_algo_ext, total_bytes


def build_datasheet(
    repo_id: str,
    source_dir: Path,
    files: List[Path],
    by_algo_split: Dict[str, Dict[str, int]],
    by_algo_ext: Dict[str, Dict[str, int]],
    total_bytes: int,
) -> str:
    created_on = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d")
    file_count = len(files)
    size_gb = total_bytes / 1e9

    algo_split_rows: List[str] = []
    for algo in sorted(by_algo_split):
        for split_name in sorted(by_algo_split[algo]):
            algo_split_rows.append(
                f"| `{algo}` | `{split_name}` | {by_algo_split[algo][split_name]} |"
            )
    if not algo_split_rows:
        algo_split_rows.append("| `n/a` | `n/a` | 0 |")

    ext_rows: List[str] = []
    for algo in sorted(by_algo_ext):
        for ext in sorted(by_algo_ext[algo]):
            ext_rows.append(f"| `{algo}` | `.{ext}` | {by_algo_ext[algo][ext]} |")
    if not ext_rows:
        ext_rows.append("| `n/a` | `n/a` | 0 |")

    example_rows: List[str] = []
    for file_path in files[:8]:
        example_rows.append(f"- `{file_path.relative_to(source_dir)}`")
    if not example_rows:
        example_rows.append("- _No files found_")

    return f"""---
license: mit
pretty_name: Round-Trip Code Compression Raw Dataset
task_categories:
- text-generation
language:
- en
size_categories:
- 1K<n<10K
---

# Round-Trip Code Compression Raw Dataset

This dataset contains raw inputs and algorithm outputs for round-trip code compression tasks across `ae`, `huffman`, `lzw`, and `rle`.

## Dataset Summary

- Repository: `{repo_id}`
- Source directory: `{source_dir.relative_to(PROJECT_ROOT)}`
- Generated on: `{created_on}`
- Total files: `{file_count}`
- Total size: `{size_gb:.3f} GB`

### Folder Breakdown

| Algorithm | Split | File count |
|---|---|---:|
{os.linesep.join(algo_split_rows)}

### File Type Breakdown

| Algorithm | Extension | File count |
|---|---|---:|
{os.linesep.join(ext_rows)}

### Example Paths
{os.linesep.join(example_rows)}

## Datasheet For Datasets

### Motivation

- **Purpose:** Provide raw data for studying LLM reasoning on invertible compression tasks.
- **Primary use:** Benchmarking forward/inverse compression prediction workflows and downstream evaluation pipelines.

### Composition

- **Instance unit:** One file corresponds to one sample artifact.
- **Core structure:** `data/raw/<algorithm>/input/*` and `data/raw/<algorithm>/output/*`.
- **Algorithms included:** AE, Huffman, LZW, RLE.
- **File formats:** plain text (`.txt`, `.log`, `.yaml`) and algorithm-specific JSON sidecars (`.json`) where applicable.

### Collection Process

- Inputs are curated/generated examples covering strings, logs, YAML/tabular-like text, and synthetic DNA-like sequences.
- Outputs are algorithm-specific compressed representations generated by project preprocessing scripts.

### Preprocessing

- No extra transformations are applied during upload.
- Original relative paths are preserved in the dataset repository.

### Uses

- **Recommended:** Reproducible preprocessing, prompt-construction experiments, and model evaluation.
- **Not recommended:** Safety-critical production decisions without additional validation.

### Distribution

- Hosted on Hugging Face Datasets.
- Repository visibility depends on upload configuration (`private` by default).

### Maintenance

- Updated by project maintainers when new raw data batches are generated.
- Dataset card is autogenerated at upload time from the current folder contents.
"""


def upload_datasheet(api: HfApi, token: str, repo_id: str, datasheet: str) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as tmp:
        tmp.write(datasheet)
        tmp_path = Path(tmp.name)
    try:
        api.upload_file(
            path_or_fileobj=str(tmp_path),
            path_in_repo="README.md",
            repo_id=repo_id,
            repo_type=REPO_TYPE,
            token=token,
            commit_message="Update dataset datasheet",
        )
    finally:
        tmp_path.unlink(missing_ok=True)


def main() -> None:
    args = parse_args()
    source_dir = args.source_dir.resolve()
    if not source_dir.exists() or not source_dir.is_dir():
        sys.exit(f"source-dir does not exist or is not a directory: {source_dir}")

    token = os.environ.get(args.token_env)
    if not token and not args.dry_run:
        sys.exit(f"{args.token_env} env var is not set.")

    files = list_files(source_dir)
    if not files:
        sys.exit(f"No files found in source-dir: {source_dir}")

    by_algo_split, by_algo_ext, total_bytes = summarize_files(source_dir, files)
    datasheet = build_datasheet(
        repo_id=args.repo_id,
        source_dir=source_dir,
        files=files,
        by_algo_split=by_algo_split,
        by_algo_ext=by_algo_ext,
        total_bytes=total_bytes,
    )

    print(f"Source dir: {source_dir}")
    print(f"Files: {len(files)}")
    print(f"Size: {total_bytes / 1e9:.3f} GB")

    if args.dry_run:
        print("\n--- Datasheet Preview (first 80 lines) ---")
        preview_lines = datasheet.splitlines()[:80]
        print("\n".join(preview_lines))
        return

    api = HfApi(token=token)
    private = not args.public
    print(f"Ensuring repo exists: {args.repo_id} (private={private})")
    create_repo(
        repo_id=args.repo_id,
        repo_type=REPO_TYPE,
        private=private,
        exist_ok=True,
        token=token,
    )

    print("Uploading data/raw contents ...")
    api.upload_folder(
        folder_path=str(source_dir),
        path_in_repo="data/raw",
        repo_id=args.repo_id,
        repo_type=REPO_TYPE,
        token=token,
        commit_message=f"Sync raw dataset ({len(files)} files)",
    )

    print("Uploading autogenerated datasheet README.md ...")
    upload_datasheet(api, token, args.repo_id, datasheet)

    print(f"Done: https://huggingface.co/datasets/{args.repo_id}")


if __name__ == "__main__":
    main()
